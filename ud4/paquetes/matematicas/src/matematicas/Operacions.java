package matematicas;

public class Operacions {
  public int sumar(int a, int b) {
    int suma = a + b;
    return suma;
  }

  public int restar(int a, int b) {
    int restar = a - b;
    return restar;
  }

  public int multiplicar(int a, int b) {
    int multiplicar = a * b;
    return multiplicar;
  }

  public int dividir(int a, int b) {

    int dividir = a / b;
    return dividir;

  }
}
